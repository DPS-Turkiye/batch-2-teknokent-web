import { describe, expect, it } from "vitest";

import {
  AMPLIFY_SAFE_JSON_CHARS,
  amplifyBlockedMessage,
  AMPLIFY_BLOCKED_MESSAGE,
  jsonFitsAmplifyWaf,
} from "@/lib/amplify-safe-body";

describe("jsonFitsAmplifyWaf", () => {
  it("accepts a small JSON body", () => {
    expect(jsonFitsAmplifyWaf({ kind: "TRANSCRIPT", transcript: [] })).toBe(
      true,
    );
  });

  it("rejects a body over the CloudFront limit", () => {
    const transcript = Array.from({ length: 80 }, (_, index) => ({
      id: `s${index}`,
      speaker: "Sudenaz Yılmaz",
      text: "x".repeat(80),
      at: "00:10",
    }));
    expect(JSON.stringify({ segments: transcript }).length).toBeGreaterThan(
      AMPLIFY_SAFE_JSON_CHARS,
    );
    expect(jsonFitsAmplifyWaf({ segments: transcript })).toBe(false);
  });

  it("detects CloudFront HTML 403 bodies", () => {
    expect(
      amplifyBlockedMessage(
        "<html><h1>403 ERROR</h1>Generated by cloudfront (CloudFront)</html>",
      ),
    ).toBe(AMPLIFY_BLOCKED_MESSAGE);
    expect(amplifyBlockedMessage({ message: "nope" })).toBeNull();
  });
});
